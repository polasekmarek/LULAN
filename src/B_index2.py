    def process_single_locality(self, loc, season):
        """Zpracuje jednu lokalitu a vrátí predikované taxony"""

        
        if season not in ["J", "P"]:
            print(f"Nepodporovaná sezóna {season}")
            return []
            
        # Získá data lokality
        cursor = self.conn.cursor()
        

        query = """SELECT 
                        l.STRAHLER,
                        l.MNM,
                        l.KM_OD_PRAM,
                        l.PLOCHA_POV,
                        l.SLOPE,
                        l.S42_X,
                        l.S42_Y
                    FROM 
                        loc l 
                    WHERE 
                        l.KOD = ?"""

            
        cursor.execute(query, (loc,))           
        
        location_data = cursor.fetchone()
        if not location_data:
            print(f"Lokalita {loc}: Nelze získat data lokality")
            return []
            
        try:
            # 1. Transformace vstupního vektoru
            transformed_vector = self.transform_vector(location_data, season)
            
            # 2. Aplikace diskriminační matice a získání parametrů podle sezóny
            if season == "J":
                final_vector = self.apply_discriminant_matrix(transformed_vector, self.discriminant_matrix_j)
                centroids = self.centroids_j
                dmatrices = self.dmatrices_j
                probabilities = self.probabilities_j
                determinants = self.determinants_j
            elif season == "P":
                final_vector = self.apply_discriminant_matrix(transformed_vector, self.discriminant_matrix_p)
                centroids = self.centroids_p
                dmatrices = self.dmatrices_p
                probabilities = self.probabilities_p
                determinants = self.determinants_p
            else:
                print(f"Lokalita {loc}: Nepodporovaná sezóna {season}")
                return []
                
            # 3. Výpočty
            diff_vectors = self.compute_diffs(final_vector, centroids)
            score_vectors = self.compute_scores(diff_vectors, dmatrices)
            distances = self.compute_distances(diff_vectors, score_vectors)
            posterior_probabilities = self.compute_prob(distances, probabilities, determinants)
            
            # 4. Aktualizace B_index_taxa_prob tabulky
            cursor = self.conn.cursor()
            
            # Vymaže předchozí POM_VAL hodnoty
            cursor.execute("UPDATE B_index_taxa_prob SET POM_VAL = NULL")
            
            # Získání řádků s podmínkou SEZONA podle sezóny
            cursor.execute("SELECT rowid, SK_ID, VAL FROM B_index_taxa_prob WHERE SEZONA = ?", (season,))
            rows = cursor.fetchall()
            
            # Výpočet a uložení zpět do POM_VAL
            for rowid, sk_id, val in rows:
                if 1 <= sk_id <= len(posterior_probabilities):
                    weighted_val = val * posterior_probabilities[sk_id - 1]
                    cursor.execute(
                        "UPDATE B_index_taxa_prob SET POM_VAL = ? WHERE rowid = ?",
                        (weighted_val, rowid)
                    )
            
            # 5. Získání finálních výsledků
            query = """
                SELECT NMX, SUM(POM_VAL) as TOTAL_POM_VAL
                FROM B_index_taxa_prob
                WHERE POM_VAL IS NOT NULL AND POM_VAL > 0
                GROUP BY NMX
                HAVING SUM(POM_VAL) > 0
                ORDER BY SUM(POM_VAL) DESC;
            """
            
            cursor.execute(query)
            results = cursor.fetchall()
            
            # Konverze na seznam tuple pro return
            predictions = [(row['NMX'], row['TOTAL_POM_VAL']) for row in results]
            
            return predictions
            
        except Exception as e:
            print(f"Chyba při zpracování lokality {loc}: {e}")
            return []
    
