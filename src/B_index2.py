    def process_all_samples(self, clear_existing=True):
        """Zpracuje všechny MZB vzorky"""
        self.connect()
        
        try:
            cursor = self.conn.cursor()
            
            # Vytvoří tabulku
            self.create_predict_taxa_table()
            
            # Volitelně vymaže existující data
            if clear_existing:
                cursor.execute("DELETE FROM predict_taxa")
                self.conn.commit()
                print("Existující predikce vymazány")
            
            # Získá všechny MZB vzorky
            cursor.execute("""
                SELECT SAMPLE_ID, date 
                FROM samples 
                WHERE TYP = 'MZB' AND date IS NOT NULL
                ORDER BY SAMPLE_ID
            """)
            
            samples = cursor.fetchall()
            print(f"Nalezeno {len(samples)} MZB vzorků k zpracování")
            
            batch_predictions = []
            batch_size = 1000
            
            for i, sample in enumerate(samples, 1):
                sample_id = sample['SAMPLE_ID']
                sample_date = sample['date']
                
                if i % 10 == 0:
                    print(f"Zpracováno {i}/{len(samples)} vzorků")
                
                predictions = self.process_single_sample(sample_id, sample_date)
                
                # Přidá predikce do batch
                for taxon, probability in predictions:
                    if probability > 0.001:  # Filtruje pouze významné predikce
                        batch_predictions.append((sample_id, taxon, probability))
                
                # Uloží batch po dosažení velikosti
                if len(batch_predictions) >= batch_size:
                    self._insert_batch_predictions(batch_predictions)
                    batch_predictions = []
            
            # Uloží zbývající predikce
            if batch_predictions:
                self._insert_batch_predictions(batch_predictions)
            
            self.conn.commit()
            print("Predikce dokončena!")
            
        except Exception as e:
            print(f"Chyba při zpracování: {e}")
            self.conn.rollback()
            raise
        finally:
            self.disconnect()
    
    def _insert_batch_predictions(self, batch_predictions):
        """Vloží batch predikcí do databáze"""
        cursor = self.conn.cursor()
        cursor.executemany("""
            INSERT INTO predict_taxa (sample_id, taxon, val)
            VALUES (?, ?, ?)
        """, batch_predictions)
        print(f"Vloženo {len(batch_predictions)} predikcí")
    
    def get_summary(self):
        """Zobrazí souhrn predikcí"""
        self.connect()
        
        try:
            cursor = self.conn.cursor()
            
            # Celkový počet predikcí
            cursor.execute("SELECT COUNT(*) FROM predict_taxa")
            total_predictions = cursor.fetchone()[0]
            
            # Počet vzorků s predikcemi
            cursor.execute("SELECT COUNT(DISTINCT sample_id) FROM predict_taxa")
            samples_with_predictions = cursor.fetchone()[0]
            
            # Top 10 nejčastějších taxonů
            cursor.execute("""
                SELECT taxon, COUNT(*) as frequency, AVG(val) as avg_probability
                FROM predict_taxa
                GROUP BY taxon
                ORDER BY frequency DESC
                LIMIT 10
            """)
            
            top_taxa = cursor.fetchall()
            
            print(f"\nSouhrn predikcí:")
            print(f"Celkový počet predikcí: {total_predictions}")
            print(f"Vzorků s predikcemi: {samples_with_predictions}")
            print("\nTop 10 nejčastějších predikovaných taxonů:")
            for row in top_taxa:
                taxon = row['taxon']
                frequency = row['frequency']
                avg_prob = row['avg_probability']
                print(f"  {taxon}: {frequency}x (průměrná pravděpodobnost: {avg_prob:.3f})")
                
        finally:
            self.disconnect()

