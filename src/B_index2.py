    def connect(self):
        """Připojí se k databázi.

        Zapisuje se do pomocných tabulek (`predict_taxa`,
        `B_index_taxa_prob`) vlastním spojením, tedy jiným, než jakým
        čte aplikace. SQLite takový zápis nepustí, dokud nad souborem
        někdo drží rozečtený dotaz — a Qt modely ho drží, dokud se
        neuvolní. Volající proto musí zámky uvolnit předem (v aplikaci
        to zařídí `databaze_pro_zapis`).

        Čekací lhůta pět sekund kryje jen krátké zdržení od jiného
        procesu, třeba synchronizačního klienta. Delší nemá smysl:
        uplatní se na každý příkaz zvlášť a zápis tu běží v cyklu přes
        vzorky, takže by se dlouhé čekání nasčítalo do minut.
        """
        self.conn = sqlite3.connect(self.db_path, timeout=5.0)
        self.conn.row_factory = sqlite3.Row
        
    def disconnect(self):
        """Odpojí se od databáze"""
        if self.conn:
            self.conn.close()
            
    def create_predict_taxa_table(self):
        """Vytvoří tabulku predict_taxa"""
        cursor = self.conn.cursor()
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS predict_taxa (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                sample_id TEXT,
                taxon TEXT,
                val INTEGER
            )
        """)
        self.conn.commit()
        
    def determine_season(self, date_str):
        """Určí sezónu podle data vzorkování"""
        try:
            date_obj = pd.to_datetime(date_str, format='%d.%m.%Y')
            month = date_obj.month
            if month in [3, 4, 5]:
                return "J"  # Jarní
            elif month in [6, 7, 8]:
                return "L"  # Letní
            elif month in [9, 10, 11]:
                return "P"  # Podzimní
            else:
                return "Z"  # Zimní
        except (ValueError, TypeError, AttributeError):
            return None
            
    #: Posuny souřadnic S-42 před vstupem do diskriminační funkce.
    POSUN_S42_Y = 5380000
    POSUN_S42_X = 3290000

    @staticmethod
    def _uprav_souradnici(hodnota, posun):
        """Převede souřadnici S-42 na vstup diskriminační funkce.

        Postup je (hodnota − posun), zaokrouhleno na celé metry a vyděleno
        deseti. Zaokrouhlení se dělá idiomem `int(x + 0.5)`, tedy přičtením
        poloviny a useknutím.

        POZOR: původní kód psal `round(x + 0.5)`, což zaokrouhluje dvakrát —
        nejprve přičte 0,5 a pak ještě zaokrouhlí. Výsledek pak vycházel
        o 0,1 vyšší, než dává oficiální nástroj ČHMÚ (9629,3 místo 9629,2).
        Do diskriminační funkce jde tato hodnota s vahou řádu 1e−5, takže se
        chyba propsala až do zařazení lokality do skupiny.
        """
        return int(hodnota - posun + 0.5) / 10

